-- Signed editorial stories published by the Press Club.
-- Drafts remain private; only rows explicitly marked published are public.
create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null check (char_length(trim(title)) between 4 and 140),
  excerpt text not null check (char_length(trim(excerpt)) between 20 and 320),
  body text not null check (char_length(trim(body)) >= 40),
  author text not null default 'The Press Club' check (char_length(trim(author)) between 2 and 100),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'published' or published_at is not null)
);

create index if not exists blog_posts_publication_index
  on public.blog_posts (published_at desc)
  where status = 'published';

alter table public.blog_posts enable row level security;

revoke all on table public.blog_posts from anon, authenticated;
grant select on table public.blog_posts to anon, authenticated;

drop policy if exists "Public can read published blog posts" on public.blog_posts;
create policy "Public can read published blog posts"
  on public.blog_posts
  for select
  to anon, authenticated
  using (status = 'published' and published_at <= now());

