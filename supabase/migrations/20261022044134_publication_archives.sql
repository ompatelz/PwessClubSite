-- Public publication metadata. Only the archive rows and PDFs are public;
-- uploads and metadata changes remain server/dashboard operations.
create table if not exists public."NNN" (
  id bigint generated by default as identity primary key,
  "Month" smallint not null check ("Month" between 1 and 12),
  "Year" smallint not null check ("Year" between 1900 and 2200),
  "Pdf_url" text not null check (length(trim("Pdf_url")) > 0),
  created_at timestamptz not null default now(),
  unique ("Month", "Year")
);

create table if not exists public."Entelechy" (
  id bigint generated by default as identity primary key,
  edition integer not null unique check (edition > 0),
  pdf_url text not null check (length(trim(pdf_url)) > 0),
  created_at timestamptz not null default now()
);

alter table public."NNN" enable row level security;
alter table public."Entelechy" enable row level security;

revoke all on table public."NNN" from anon, authenticated;
revoke all on table public."Entelechy" from anon, authenticated;
grant select on table public."NNN" to anon, authenticated;
grant select on table public."Entelechy" to anon, authenticated;

drop policy if exists "Public can read NNN editions" on public."NNN";
create policy "Public can read NNN editions"
  on public."NNN"
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can read Entelechy editions" on public."Entelechy";
create policy "Public can read Entelechy editions"
  on public."Entelechy"
  for select
  to anon, authenticated
  using (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('NNN', 'NNN', true, 52428800, array['application/pdf']::text[]),
  ('Entelechy', 'Entelechy', true, 52428800, array['application/pdf']::text[])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;
